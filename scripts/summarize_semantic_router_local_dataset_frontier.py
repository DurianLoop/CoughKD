from __future__ import annotations

import json
from pathlib import Path
from typing import Any

import pandas as pd


ROOT = Path(__file__).resolve().parents[1]
RUNS = ROOT / "runs"
OUT = RUNS / "semantic_router_local_dataset_frontier"


READINESS = RUNS / "local_external_target_readiness" / "local_external_target_readiness.csv"
VIRUFYSEG_C = RUNS / "virufyseg_subject_ensemble_candidate_c_delta" / "subject_ensemble_delta.json"
VIRUFYSEG_KD = RUNS / "virufyseg_subject_ensemble_kd_delta" / "subject_ensemble_delta.json"
TOSCOVID2022_AUDIT = RUNS / "toscovid2022_local_candidate_audit" / "toscovid2022_local_candidate_audit.json"


MAIN_TARGETS = {"coughvid", "toscovid2021_test", "toscovid2021", "toscovid"}
SOURCE_TARGETS = {"coswara_cough", "real_coswara_cough"}
METADATA_ONLY_TARGETS = {"ukcovid_open", "ukcovid_open_test"}


def _read_json(path: Path) -> dict[str, Any]:
    if not path.is_file():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def _fmt(value: Any) -> str:
    if value is None:
        return ""
    if isinstance(value, float):
        return f"{value:.6f}"
    return str(value)


def _table(rows: list[dict[str, Any]]) -> str:
    if not rows:
        return "_No rows._"
    cols = list(rows[0])
    lines = [
        "| " + " | ".join(cols) + " |",
        "| " + " | ".join(["---"] * len(cols)) + " |",
    ]
    for row in rows:
        lines.append("| " + " | ".join(_fmt(row.get(col)) for col in cols) + " |")
    return "\n".join(lines)


def _latex_stress_table(rows: list[dict[str, Any]]) -> str:
    def esc(value: Any) -> str:
        text = _fmt(value)
        return (
            text.replace("%", r"\%")
            .replace("_", r"\_")
            .replace("<", r"$<$")
            .replace(">", r"$>$")
        )

    if not rows:
        return "% No local stress rows available.\n"
    lines = [
        "% Auto-generated by scripts/summarize_semantic_router_local_dataset_frontier.py",
        r"\begin{table}[t]",
        r"\centering",
        r"\scriptsize",
        r"\caption{Local Virufyseg subject-ensemble stress evidence. Deltas are AUROC points relative to the source-only seed ensemble. Resampling unit is subject ID; the target has only 16 independent subjects, so this is auxiliary stress evidence rather than a third-target validation.}",
        r"\label{tab:local_virufyseg_stress}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Candidate & Subjects & Delta & 95\% CI low & 95\% CI high & P(delta$\leq$0) \\",
        r"\midrule",
    ]
    for row in rows:
        lines.append(
            " & ".join(
                [
                    esc(row["candidate"]),
                    esc(row["subjects"]),
                    esc(row["delta"]),
                    esc(row["ci95_low"]),
                    esc(row["ci95_high"]),
                    esc(row["p_delta_le_0"]),
                ]
            )
            + r" \\"
        )
    lines.extend(
        [
            r"\bottomrule",
            r"\end{tabular}",
            "}",
            r"\end{table}",
            "",
        ]
    )
    return "\n".join(lines)


def _role(row: pd.Series) -> str:
    target = str(row["target_guess"])
    rows = int(row["rows"])
    subjects = int(row["subjects"])
    pred_runs = int(row["prediction_runs"])
    audio_fraction = float(row["audio_found_fraction"] or 0.0)
    if target in SOURCE_TARGETS:
        return "source_domain_not_external_target"
    if target in MAIN_TARGETS:
        return "already_main_semantic_router_target"
    if target in METADATA_ONLY_TARGETS:
        return "metadata_ready_audio_missing"
    if pred_runs > 0 and audio_fraction >= 0.95 and subjects < 50:
        return "auxiliary_micro_stress_target"
    if pred_runs > 0 and audio_fraction >= 0.95 and subjects >= 200:
        return "candidate_local_third_target"
    if audio_fraction >= 0.95 and pred_runs == 0:
        return "audio_ready_predictions_missing"
    return "not_ready"


def main() -> None:
    if not READINESS.is_file():
        raise SystemExit(f"missing readiness table: {READINESS}")
    df = pd.read_csv(READINESS)
    rows = []
    for _, row in df.iterrows():
        rows.append(
            {
                "manifest": row["manifest"],
                "target_guess": row["target_guess"],
                "rows": int(row["rows"]),
                "subjects": int(row["subjects"]),
                "audio_fraction": float(row["audio_found_fraction"] or 0.0),
                "prediction_runs": int(row["prediction_runs"]),
                "structured_symptoms": bool(row["structured_key_value_symptoms"]),
                "role": _role(row),
            }
        )

    local_third = [row for row in rows if row["role"] == "candidate_local_third_target"]
    auxiliary = [row for row in rows if row["role"] == "auxiliary_micro_stress_target"]
    source_ready = [row for row in rows if row["role"] == "source_domain_not_external_target" and row["audio_fraction"] >= 0.95]
    audio_ready_missing_predictions = [row for row in rows if row["role"] == "audio_ready_predictions_missing"]

    virufyseg = {
        "candidate_c": _read_json(VIRUFYSEG_C),
        "kd": _read_json(VIRUFYSEG_KD),
    }
    toscovid2022 = _read_json(TOSCOVID2022_AUDIT)
    stress_rows = []
    for name, payload in virufyseg.items():
        if not payload:
            continue
        stress_rows.append(
            {
                "target": payload.get("target", ""),
                "candidate": payload.get("candidate", name),
                "subjects": payload.get("n_subjects"),
                "delta": payload.get("point_delta"),
                "ci95_low": payload.get("ci95_low"),
                "ci95_high": payload.get("ci95_high"),
                "p_delta_le_0": payload.get("p_delta_le_0"),
                "p_delta_lt_3pt": payload.get("p_delta_lt_0_03"),
            }
        )

    verdict = "NO_LOCAL_THIRD_TARGET_READY"
    next_action = (
        "Use existing COUGHVID/TosCOVID as the two main targets, keep Virufy/Virufyseg as auxiliary "
        "micro-stress evidence, and do not claim a third robust external target from local data alone."
    )
    if local_third:
        verdict = "LOCAL_THIRD_TARGET_READY"
        next_action = "Run the semantic-router audit on the candidate local third target before changing the paper claim."

    payload = {
        "verdict": verdict,
        "next_action": next_action,
        "local_third_targets": local_third,
        "auxiliary_micro_stress_targets": auxiliary,
        "source_domain_audio_ready": source_ready,
        "audio_ready_predictions_missing": audio_ready_missing_predictions,
        "raw_metadata_only_candidates": [toscovid2022] if toscovid2022 else [],
        "virufyseg_subject_ensemble_stress": stress_rows,
        "evidence_paths": {
            "readiness": str(READINESS.relative_to(ROOT)),
            "virufyseg_candidate_c_delta": str(VIRUFYSEG_C.relative_to(ROOT)),
            "virufyseg_kd_delta": str(VIRUFYSEG_KD.relative_to(ROOT)),
            "toscovid2022_local_candidate_audit": str(TOSCOVID2022_AUDIT.relative_to(ROOT)),
        },
    }

    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "semantic_router_local_dataset_frontier.json").write_text(
        json.dumps(payload, indent=2),
        encoding="utf-8",
    )

    lines = [
        "# Semantic-Router Local Dataset Frontier",
        "",
        f"- Verdict: `{verdict}`",
        f"- Next action: {next_action}",
        "",
        "## Local Manifest Roles",
        "",
        _table(rows),
        "",
        "## Virufyseg Subject-Ensemble Stress Evidence",
        "",
        _table(stress_rows),
        "",
        "## Raw Metadata-Only Candidates",
        "",
        _table(
            [
                {
                    "candidate": "TosCOVID 2022",
                    "verdict": toscovid2022.get("verdict", "missing"),
                    "rows": toscovid2022.get("csv_2022_rows", ""),
                    "unique_ids": toscovid2022.get("csv_2022_unique_ids", ""),
                    "audio_dirs": ",".join(toscovid2022.get("local_audio_dirs", [])),
                    "audio_overlap": toscovid2022.get("id_overlap_with_audio_2021_keys", ""),
                    "role": toscovid2022.get("claim_role", ""),
                }
            ]
            if toscovid2022
            else []
        ),
        "",
        "## Decision Boundary",
        "",
        "- Coswara is audio-ready but is the source domain, so it should not be counted as an external third target.",
        "- COUGHVID and TosCOVID are already the main semantic-router evidence targets.",
        "- Virufy and Virufyseg are local and prediction-ready, but their effective independent sample size is 16 subjects.",
        "- TosCOVID 2022 is present locally as a metadata/testing table, but no matching local audio directory or audio-path manifest is available.",
        "- Therefore local-only evidence can strengthen the supplement as a micro stress test, but it should not upgrade the paper to a three-target robust claim.",
        "",
    ]
    (OUT / "SEMANTIC_ROUTER_LOCAL_DATASET_FRONTIER.md").write_text(
        "\n".join(lines),
        encoding="utf-8",
    )
    (OUT / "virufyseg_subject_ensemble_stress.tex").write_text(
        _latex_stress_table(stress_rows),
        encoding="utf-8",
    )
    print(json.dumps(payload, indent=2))
    print(OUT / "SEMANTIC_ROUTER_LOCAL_DATASET_FRONTIER.md")


if __name__ == "__main__":
    main()
